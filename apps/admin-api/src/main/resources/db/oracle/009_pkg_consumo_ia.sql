CREATE OR REPLACE TRIGGER trg_log_alerta_consumo
AFTER INSERT OR UPDATE OR DELETE ON alerta_consumo
FOR EACH ROW
DECLARE
  v_operacao   VARCHAR2(10);
  v_alerta_id  alerta_consumo.id%TYPE;
  v_usuario_id alerta_consumo.usuario_id%TYPE;
  v_total      alerta_consumo.total_tokens%TYPE;
  v_mensagem   alerta_consumo.mensagem%TYPE;
BEGIN
  IF INSERTING THEN
    v_operacao := 'INSERT';
    v_alerta_id := :NEW.id;
    v_usuario_id := :NEW.usuario_id;
    v_total := :NEW.total_tokens;
    v_mensagem := :NEW.mensagem;
  ELSIF UPDATING THEN
    v_operacao := 'UPDATE';
    v_alerta_id := :NEW.id;
    v_usuario_id := :NEW.usuario_id;
    v_total := :NEW.total_tokens;
    v_mensagem := :NEW.mensagem;
  ELSE
    v_operacao := 'DELETE';
    v_alerta_id := :OLD.id;
    v_usuario_id := :OLD.usuario_id;
    v_total := :OLD.total_tokens;
    v_mensagem := :OLD.mensagem;
  END IF;

  INSERT INTO log_alerta_consumo (
    alerta_id, operacao, usuario_id, total_tokens, mensagem
  ) VALUES (
    v_alerta_id, v_operacao, v_usuario_id, v_total, v_mensagem
  );
END trg_log_alerta_consumo;
/

