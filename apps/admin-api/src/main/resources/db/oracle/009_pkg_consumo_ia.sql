DECLARE
  PROCEDURE garantir_tabela(p_nome IN VARCHAR2, p_ddl IN VARCHAR2) IS
    v_count NUMBER;
  BEGIN
    SELECT COUNT(*)
      INTO v_count
      FROM user_tables
     WHERE table_name = p_nome;

    IF v_count = 0 THEN
      EXECUTE IMMEDIATE p_ddl;
    END IF;
  END;

  PROCEDURE garantir_indice(p_nome IN VARCHAR2, p_ddl IN VARCHAR2) IS
    v_count NUMBER;
  BEGIN
    SELECT COUNT(*)
      INTO v_count
      FROM user_indexes
     WHERE index_name = p_nome;

    IF v_count = 0 THEN
      EXECUTE IMMEDIATE p_ddl;
    END IF;
  END;
BEGIN
  garantir_tabela(
    'LOG_ALERTA_CONSUMO',
    'CREATE TABLE LOG_ALERTA_CONSUMO (
       ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
       ALERTA_ID NUMBER,
       OPERACAO VARCHAR2(10 CHAR) NOT NULL,
       USUARIO_ID NUMBER,
       TOTAL_TOKENS NUMBER(12),
       MENSAGEM VARCHAR2(400 CHAR),
       REGISTRADO_EM TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
     )'
  );
  garantir_indice(
    'IX_LOG_ALERTA_USUARIO',
    'CREATE INDEX IX_LOG_ALERTA_USUARIO ON LOG_ALERTA_CONSUMO (USUARIO_ID, REGISTRADO_EM)'
  );
END;
/

