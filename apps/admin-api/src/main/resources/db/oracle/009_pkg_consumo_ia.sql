CREATE OR REPLACE PACKAGE BODY pkg_consumo_ia AS

  FUNCTION fn_indicador_tokens (
    p_usuario_id IN usuario_consumo.id%TYPE,
    p_inicio     IN TIMESTAMP,
    p_fim        IN TIMESTAMP
  ) RETURN NUMBER
  IS
    e_usuario_inexistente EXCEPTION;
    e_periodo_invalido    EXCEPTION;
    v_existe              NUMBER;
    v_total               NUMBER;
  BEGIN
    IF p_inicio IS NULL OR p_fim IS NULL OR p_inicio > p_fim THEN
      RAISE e_periodo_invalido;
    END IF;

    IF p_usuario_id IS NULL THEN
      RAISE e_usuario_inexistente;
    END IF;

    SELECT COUNT(*)
      INTO v_existe
      FROM usuario_consumo
     WHERE id = p_usuario_id;

    IF v_existe = 0 THEN
      RAISE e_usuario_inexistente;
    END IF;

    SELECT NVL(SUM(quantidade_tokens), 0)
      INTO v_total
      FROM leitura_consumo
     WHERE usuario_id = p_usuario_id
       AND instante >= p_inicio
       AND instante <= p_fim;

    RETURN v_total;
  EXCEPTION
    WHEN e_usuario_inexistente THEN
      RAISE_APPLICATION_ERROR(-20001, 'Usuário de consumo inexistente.');
    WHEN e_periodo_invalido THEN
      RAISE_APPLICATION_ERROR(-20002, 'Período inválido: início posterior ao fim.');
    WHEN OTHERS THEN
      RAISE;
  END fn_indicador_tokens;

  FUNCTION fn_consumo_formatado (
    p_usuario_id IN usuario_consumo.id%TYPE,
    p_inicio     IN TIMESTAMP,
    p_fim        IN TIMESTAMP
  ) RETURN VARCHAR2
  IS
    v_total  NUMBER;
    v_nome   usuario_consumo.nome%TYPE;
    v_status VARCHAR2(20);
  BEGIN
    v_total := fn_indicador_tokens(p_usuario_id, p_inicio, p_fim);

    SELECT nome
      INTO v_nome
      FROM usuario_consumo
     WHERE id = p_usuario_id;

    IF v_total >= c_limite_padrao THEN
      v_status := 'Consumo alto.';
    ELSE
      v_status := 'Consumo normal.';
    END IF;

    RETURN v_nome
      || ' consumiu '
      || TO_CHAR(v_total, 'FM999999999999')
      || ' tokens no período. '
      || v_status;
  EXCEPTION
    WHEN OTHERS THEN
      RAISE;
  END fn_consumo_formatado;

  PROCEDURE pr_registrar_alerta_consumo (
    p_usuario_id IN  usuario_consumo.id%TYPE,
    p_inicio     IN  TIMESTAMP,
    p_fim        IN  TIMESTAMP,
    p_limite     IN  NUMBER DEFAULT 10000,
    p_alerta_id  OUT alerta_consumo.id%TYPE
  ) IS
    e_usuario_inexistente EXCEPTION;
    e_periodo_invalido    EXCEPTION;
    e_limite_invalido     EXCEPTION;
    PRAGMA EXCEPTION_INIT(e_usuario_inexistente, -20001);
    PRAGMA EXCEPTION_INIT(e_periodo_invalido, -20002);
    PRAGMA EXCEPTION_INIT(e_limite_invalido, -20003);
    v_limite   NUMBER;
    v_total    NUMBER;
    v_nome     usuario_consumo.nome%TYPE;
    v_mensagem alerta_consumo.mensagem%TYPE;
  BEGIN
    p_alerta_id := NULL;
    v_limite := NVL(p_limite, c_limite_padrao);

    IF p_inicio IS NULL OR p_fim IS NULL OR p_inicio > p_fim THEN
      RAISE e_periodo_invalido;
    END IF;

    IF v_limite < 0 THEN
      RAISE e_limite_invalido;
    END IF;

    v_total := fn_indicador_tokens(p_usuario_id, p_inicio, p_fim);

    IF v_total < v_limite THEN
      RETURN;
    END IF;

    BEGIN
      SELECT id
        INTO p_alerta_id
        FROM alerta_consumo
       WHERE usuario_id = p_usuario_id
         AND inicio = p_inicio
         AND fim = p_fim;
      RETURN;
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        NULL;
    END;

    SELECT nome
      INTO v_nome
      FROM usuario_consumo
     WHERE id = p_usuario_id;

    v_mensagem := v_nome
      || ' consumiu '
      || TO_CHAR(v_total, 'FM999999999999')
      || ' tokens no período. Consumo alto.';

    INSERT INTO alerta_consumo (
      usuario_id, inicio, fim, total_tokens, mensagem
    ) VALUES (
      p_usuario_id, p_inicio, p_fim, v_total, v_mensagem
    ) RETURNING id INTO p_alerta_id;
  EXCEPTION
    WHEN e_periodo_invalido THEN
      RAISE_APPLICATION_ERROR(-20002, 'Período inválido: início posterior ao fim.');
    WHEN e_usuario_inexistente THEN
      RAISE_APPLICATION_ERROR(-20001, 'Usuário de consumo inexistente.');
    WHEN e_limite_invalido THEN
      RAISE_APPLICATION_ERROR(-20003, 'Limite de consumo inválido.');
    WHEN DUP_VAL_ON_INDEX THEN
      SELECT id
        INTO p_alerta_id
        FROM alerta_consumo
       WHERE usuario_id = p_usuario_id
         AND inicio = p_inicio
         AND fim = p_fim;
    WHEN OTHERS THEN
      RAISE;
  END pr_registrar_alerta_consumo;

  PROCEDURE pr_relatorio_consumo (
    p_inicio    IN  TIMESTAMP,
    p_fim       IN  TIMESTAMP,
    p_resultado OUT SYS_REFCURSOR
  ) IS
    e_periodo_invalido EXCEPTION;
    CURSOR c_usuarios IS
      SELECT id, nome
        FROM usuario_consumo
       ORDER BY id;
    v_total      NUMBER;
    v_qtd_alerta NUMBER;
    v_tem_alerta NUMBER(1);
  BEGIN
    DELETE FROM relatorio_consumo_tmp;

    IF p_inicio IS NULL OR p_fim IS NULL OR p_inicio > p_fim THEN
      RAISE e_periodo_invalido;
    END IF;

    FOR r_usuario IN c_usuarios LOOP
      v_total := fn_indicador_tokens(r_usuario.id, p_inicio, p_fim);

      SELECT COUNT(*)
        INTO v_qtd_alerta
        FROM alerta_consumo
       WHERE usuario_id = r_usuario.id
         AND inicio = p_inicio
         AND fim = p_fim;

      IF v_qtd_alerta > 0 THEN
        v_tem_alerta := 1;
      ELSE
        v_tem_alerta := 0;
      END IF;

      INSERT INTO relatorio_consumo_tmp (
        usuario_id, nome, total_tokens, tem_alerta
      ) VALUES (
        r_usuario.id, r_usuario.nome, v_total, v_tem_alerta
      );
    END LOOP;

    OPEN p_resultado FOR
      SELECT usuario_id, nome, total_tokens, tem_alerta
        FROM relatorio_consumo_tmp
       ORDER BY usuario_id;
  EXCEPTION
    WHEN e_periodo_invalido THEN
      RAISE_APPLICATION_ERROR(-20002, 'Período inválido: início posterior ao fim.');
    WHEN OTHERS THEN
      DELETE FROM relatorio_consumo_tmp;
      RAISE;
  END pr_relatorio_consumo;

  FUNCTION fn_consultar_total_dinamico (
    p_origem     IN VARCHAR2,
    p_usuario_id IN usuario_consumo.id%TYPE
  ) RETURN NUMBER
  IS
    v_sql    VARCHAR2(400);
    v_origem VARCHAR2(30) := UPPER(TRIM(p_origem));
    v_total  NUMBER;
  BEGIN
    IF p_usuario_id IS NULL THEN
      RAISE_APPLICATION_ERROR(-20001, 'Usuário de consumo inexistente.');
    END IF;

    -- Origem escolhe a sentença. O id entra por bind, nunca concatenado.
    CASE v_origem
      WHEN 'LEITURA' THEN
        v_sql := 'SELECT NVL(SUM(quantidade_tokens), 0)
                    FROM leitura_consumo
                   WHERE usuario_id = :id';
      WHEN 'ALERTA' THEN
        v_sql := 'SELECT COUNT(*)
                    FROM alerta_consumo
                   WHERE usuario_id = :id';
      WHEN 'LOG' THEN
        v_sql := 'SELECT COUNT(*)
                    FROM log_alerta_consumo
                   WHERE usuario_id = :id';
      ELSE
        RAISE_APPLICATION_ERROR(-20004, 'Origem de consulta não permitida.');
    END CASE;

    EXECUTE IMMEDIATE v_sql INTO v_total USING p_usuario_id;
    RETURN v_total;
  END fn_consultar_total_dinamico;

END pkg_consumo_ia;
/

